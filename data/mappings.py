# ---------------------------------------------------------------------------
# Reverse table: x86 → PPC
# Built by inverting PPC_TO_X86; one x86 mnemonic may map back to many PPCs.
# ---------------------------------------------------------------------------

def _build_x86_to_ppc() -> dict[str, MappingEntry]:
    """Invert PPC_TO_X86, grouping all PPC sources per x86 target."""
    # Accumulate: x86_mnemonic → list of (ppc_mnemonic, confidence, notes, mode)
    from collections import defaultdict
    buckets: dict[str, list] = defaultdict(list)

    for ppc_m, entry in PPC_TO_X86.items():
        for x86_m in entry.targets:
            buckets[x86_m].append((ppc_m, entry.confidence, entry.notes, entry.mode))

    result: dict[str, MappingEntry] = {}
    for x86_m, sources in buckets.items():
        # Pick the best (lowest) confidence and collect all PPC mnemonics
        order = ["direct", "close", "suggestion", "none"]
        best_conf = min(sources, key=lambda t: order.index(t[1]))[1]
        ppc_targets = [s[0] for s in sources]
        notes_parts = list({s[2] for s in sources})  # deduplicate
        notes = " | ".join(notes_parts[:3])           # cap to 3 for readability
        modes = list({s[3] for s in sources})
        mode = "both" if len(modes) > 1 or modes[0] == "both" else modes[0]

        result[x86_m] = MappingEntry(
            source=x86_m,
            targets=ppc_targets,
            confidence=best_conf,
            notes=notes,
            mode=mode,
        )

    return result


X86_TO_PPC: dict[str, MappingEntry] = _build_x86_to_ppc()
