"""
mappings.py — PPC ↔ x86 instruction mapping table.

Exports
-------
MappingEntry   dataclass describing a single mapping
PPC_TO_X86     dict[str, MappingEntry]  — keyed by lowercase PPC mnemonic
X86_TO_PPC     dict[str, MappingEntry]  — keyed by uppercase x86 mnemonic
               (built automatically by inverting PPC_TO_X86)

Confidence levels
-----------------
"direct"     — near-identical semantics; safe 1-to-1 substitution
"close"      — same intent, minor semantic/register-model differences
"suggestion" — closest approximation; programmer must verify
"none"       — no reasonable analogue; noted for completeness
"""

